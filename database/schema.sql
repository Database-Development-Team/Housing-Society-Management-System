
-- =====================================
-- TABLE 1: OWNER
-- =====================================

CREATE TABLE OWNER
(
    OWNER_ID NUMBER,

    FIRST_NAME VARCHAR2(50) NOT NULL,

    LAST_NAME VARCHAR2(50) NOT NULL,

    CNIC_NUMBER VARCHAR2(15) NOT NULL,

    MOBILE_NUMBER VARCHAR2(15),

    EMAIL_ADDRESS VARCHAR2(100),

    REGISTRATION_DATE DATE DEFAULT SYSDATE,

    CONSTRAINT PK_OWNER
        PRIMARY KEY (OWNER_ID),

    CONSTRAINT UQ_OWNER_CNIC
        UNIQUE (CNIC_NUMBER)
);

-- =====================================
-- TABLE 2: TENANT
-- =====================================

CREATE TABLE TENANT
(
    TENANT_ID NUMBER,

    FULL_NAME VARCHAR2(100) NOT NULL,

    CNIC_NUMBER VARCHAR2(15) NOT NULL,

    CONTACT_NUMBER VARCHAR2(15),

    FAMILY_MEMBERS_COUNT NUMBER(3) DEFAULT 0,

    ADDRESS_PROOF VARCHAR2(255),

    REGISTRATION_DATE DATE DEFAULT SYSDATE,

    CONSTRAINT PK_TENANT
        PRIMARY KEY (TENANT_ID),

    CONSTRAINT UQ_TENANT_CNIC
        UNIQUE (CNIC_NUMBER),

    CONSTRAINT CHK_TENANT_FAMILY_COUNT
        CHECK (FAMILY_MEMBERS_COUNT >= 0)
);

-- =====================================
-- TABLE 3: EMPLOYEE
-- =====================================

CREATE TABLE EMPLOYEE
(
    EMPLOYEE_ID NUMBER,

    EMP_FULL_NAME VARCHAR2(100) NOT NULL,

    JOB_ROLE VARCHAR2(50) NOT NULL,

    SHIFT_TIMING VARCHAR2(50),

    MONTHLY_SALARY NUMBER(10,2) NOT NULL,

    CONTACT_NUMBER VARCHAR2(15),

    CNIC_NUMBER VARCHAR2(15) NOT NULL,

    HIRE_DATE DATE DEFAULT SYSDATE,

    STATUS VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT PK_EMPLOYEE
        PRIMARY KEY (EMPLOYEE_ID),

    CONSTRAINT UQ_EMPLOYEE_CNIC
        UNIQUE (CNIC_NUMBER),

    CONSTRAINT CHK_EMPLOYEE_SALARY
        CHECK (MONTHLY_SALARY >= 0),

    CONSTRAINT CHK_EMPLOYEE_STATUS
        CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

-- =====================================
-- TABLE 4: FACILITY
-- =====================================

CREATE TABLE FACILITY
(
    FACILITY_ID NUMBER,

    FACILITY_NAME VARCHAR2(100) NOT NULL,

    LOCATION_BLOCK VARCHAR2(50) NOT NULL,

    MAX_CAPACITY NUMBER(5) NOT NULL,

    OPERATIONAL_HOURS VARCHAR2(100),

    BOOKING_FEE NUMBER(10,2) DEFAULT 0 NOT NULL,

    MAINTENANCE_SCHEDULE VARCHAR2(255),

    OPERATIONAL_STATUS VARCHAR2(10)
        DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT PK_FACILITY
        PRIMARY KEY (FACILITY_ID),

    CONSTRAINT CHK_FACILITY_CAPACITY
        CHECK (MAX_CAPACITY > 0),

    CONSTRAINT CHK_FACILITY_FEE
        CHECK (BOOKING_FEE >= 0),

    CONSTRAINT CHK_FACILITY_STATUS
        CHECK (OPERATIONAL_STATUS IN ('ACTIVE', 'INACTIVE'))
);

-- =====================================
-- TABLE 5: HOUSE
-- =====================================

CREATE TABLE HOUSE
(
    HOUSE_ID NUMBER,

    HOUSE_NO VARCHAR2(20) NOT NULL,

    STREET_NUMBER VARCHAR2(20) NOT NULL,

    BLOCK_NAME VARCHAR2(50) NOT NULL,

    SIZE_IN_MARLA NUMBER(6,2) NOT NULL,

    CONSTRUCTION_STATUS VARCHAR2(25)
        DEFAULT 'COMPLETED' NOT NULL,

    OCCUPANCY_STATUS VARCHAR2(20)
        DEFAULT 'VACANT' NOT NULL,

    OWNER_ID NUMBER NOT NULL,

    CONSTRAINT PK_HOUSE
        PRIMARY KEY (HOUSE_ID),

    CONSTRAINT FK_HOUSE_OWNER
        FOREIGN KEY (OWNER_ID)
        REFERENCES OWNER(OWNER_ID),

    CONSTRAINT UQ_HOUSE_LOCATION
        UNIQUE (BLOCK_NAME, STREET_NUMBER, HOUSE_NO),

    CONSTRAINT CHK_HOUSE_SIZE
        CHECK (SIZE_IN_MARLA > 0),

    CONSTRAINT CHK_HOUSE_CONSTRUCTION_STATUS
        CHECK (CONSTRUCTION_STATUS IN
            ('COMPLETED', 'UNDER_CONSTRUCTION', 'RENOVATING')),

    CONSTRAINT CHK_HOUSE_OCCUPANCY_STATUS
        CHECK (OCCUPANCY_STATUS IN
            ('OWNER-OCCUPIED', 'TENANT-OCCUPIED', 'VACANT'))
);

-- =====================================
-- TABLE 6: LEASE
-- =====================================

CREATE TABLE LEASE
(
    LEASE_ID NUMBER,

    HOUSE_ID NUMBER NOT NULL,

    TENANT_ID NUMBER NOT NULL,

    LEASE_START_DATE DATE NOT NULL,

    LEASE_END_DATE DATE NOT NULL,

    RENT_AMOUNT NUMBER(10,2) NOT NULL,

    POLICE_VERIFICATION_STATUS VARCHAR2(20)
        DEFAULT 'PENDING' NOT NULL,

    LEASE_STATUS VARCHAR2(20)
        DEFAULT 'PENDING' NOT NULL,

    CONSTRAINT PK_LEASE
        PRIMARY KEY (LEASE_ID),

    CONSTRAINT FK_LEASE_HOUSE
        FOREIGN KEY (HOUSE_ID)
        REFERENCES HOUSE(HOUSE_ID),

    CONSTRAINT FK_LEASE_TENANT
        FOREIGN KEY (TENANT_ID)
        REFERENCES TENANT(TENANT_ID),

    CONSTRAINT CHK_LEASE_DATES
        CHECK (LEASE_END_DATE > LEASE_START_DATE),

    CONSTRAINT CHK_LEASE_RENT
        CHECK (RENT_AMOUNT > 0),

    CONSTRAINT CHK_LEASE_POLICE_STATUS
        CHECK (POLICE_VERIFICATION_STATUS IN
            ('PENDING', 'VERIFIED', 'REJECTED')),

    CONSTRAINT CHK_LEASE_STATUS
        CHECK (LEASE_STATUS IN
            ('PENDING', 'ACTIVE', 'EXPIRED', 'TERMINATED'))
);

-- ONLY ONE ACTIVE LEASE PER HOUSE

CREATE UNIQUE INDEX UQ_LEASE_ACTIVE_HOUSE
ON LEASE
(
    CASE
        WHEN LEASE_STATUS = 'ACTIVE'
        THEN HOUSE_ID
        ELSE NULL
    END
);

-- =====================================
-- TABLE 7: RESIDENT
-- =====================================

CREATE TABLE RESIDENT
(
    RESIDENT_ID NUMBER,

    FULL_NAME VARCHAR2(100) NOT NULL,

    CNIC_NUMBER VARCHAR2(15),

    CONTACT_NUMBER VARCHAR2(15),

    RELATION_TYPE VARCHAR2(20) NOT NULL,

    MOVE_IN_DATE DATE DEFAULT SYSDATE NOT NULL,

    MOVE_OUT_DATE DATE,

    HOUSE_ID NUMBER NOT NULL,

    TENANT_ID NUMBER,

    OWNER_ID NUMBER,

    CONSTRAINT PK_RESIDENT
        PRIMARY KEY (RESIDENT_ID),

    CONSTRAINT UQ_RESIDENT_CNIC
        UNIQUE (CNIC_NUMBER),

    CONSTRAINT FK_RESIDENT_HOUSE
        FOREIGN KEY (HOUSE_ID)
        REFERENCES HOUSE(HOUSE_ID),

    CONSTRAINT FK_RESIDENT_TENANT
        FOREIGN KEY (TENANT_ID)
        REFERENCES TENANT(TENANT_ID),

    CONSTRAINT FK_RESIDENT_OWNER
        FOREIGN KEY (OWNER_ID)
        REFERENCES OWNER(OWNER_ID),

    CONSTRAINT CHK_RESIDENT_DATES
        CHECK (
            MOVE_OUT_DATE IS NULL
            OR MOVE_OUT_DATE >= MOVE_IN_DATE
        ),

    CONSTRAINT CHK_RESIDENT_TYPE
        CHECK (RELATION_TYPE IN
            ('OWNER', 'TENANT', 'FAMILY_MEMBER', 'OTHER')),

    CONSTRAINT CHK_RESIDENT_ROLE_LINK
        CHECK
        (
            (RELATION_TYPE = 'OWNER'
                AND OWNER_ID IS NOT NULL
                AND TENANT_ID IS NULL)

            OR

            (RELATION_TYPE = 'TENANT'
                AND TENANT_ID IS NOT NULL
                AND OWNER_ID IS NULL)

            OR

            (RELATION_TYPE IN ('FAMILY_MEMBER', 'OTHER')
                AND OWNER_ID IS NULL
                AND TENANT_ID IS NULL)
        )
);

-- =====================================
-- TABLE 8: VEHICLE
-- =====================================

CREATE TABLE VEHICLE
(
    VEHICLE_ID NUMBER,

    LICENSE_PLATE_NO VARCHAR2(20) NOT NULL,

    VEHICLE_MAKE VARCHAR2(50) NOT NULL,

    VEHICLE_MODEL VARCHAR2(50),

    VEHICLE_COLOR VARCHAR2(30),

    PARKING_STICKER_NO VARCHAR2(30),

    STICKER_EXPIRY_DATE DATE,

    RESIDENT_ID NUMBER NOT NULL,

    CONSTRAINT PK_VEHICLE
        PRIMARY KEY (VEHICLE_ID),

    CONSTRAINT UQ_VEHICLE_LICENSE
        UNIQUE (LICENSE_PLATE_NO),

    CONSTRAINT UQ_VEHICLE_STICKER
        UNIQUE (PARKING_STICKER_NO),

    CONSTRAINT FK_VEHICLE_RESIDENT
        FOREIGN KEY (RESIDENT_ID)
        REFERENCES RESIDENT(RESIDENT_ID)
);
