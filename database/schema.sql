-- =====================================
-- TABLE 10: MAINTENANCE_BILL
-- =====================================

CREATE TABLE MAINTENANCE_BILL
(
    BILL_ID NUMBER,

    BILLING_MONTH DATE NOT NULL,

    TOTAL_AMOUNT NUMBER(10,2) NOT NULL,

    DUE_DATE DATE NOT NULL,

    PAYMENT_STATUS VARCHAR2(10)
        DEFAULT 'UNPAID' NOT NULL,

    PAYMENT_DATE DATE,

    PAYMENT_METHOD VARCHAR2(20),

    HOUSE_ID NUMBER NOT NULL,

    EMPLOYEE_ID NUMBER NOT NULL,

    CONSTRAINT PK_MAINTENANCE_BILL
        PRIMARY KEY (BILL_ID),

    CONSTRAINT FK_MAINT_BILL_HOUSE
        FOREIGN KEY (HOUSE_ID)
        REFERENCES HOUSE(HOUSE_ID),

    CONSTRAINT FK_MAINT_BILL_EMPLOYEE
        FOREIGN KEY (EMPLOYEE_ID)
        REFERENCES EMPLOYEE(EMPLOYEE_ID),

    CONSTRAINT UQ_MAINT_BILL_MONTH
        UNIQUE (HOUSE_ID, BILLING_MONTH),

    CONSTRAINT CHK_MAINT_BILL_AMOUNT
        CHECK (TOTAL_AMOUNT >= 0),

    CONSTRAINT CHK_MAINT_BILL_MONTH
        CHECK (
            BILLING_MONTH = TRUNC(BILLING_MONTH, 'MM')
        ),

    CONSTRAINT CHK_MAINT_BILL_DUE_DATE
        CHECK (DUE_DATE >= BILLING_MONTH),

    CONSTRAINT CHK_MAINT_BILL_STATUS
        CHECK (PAYMENT_STATUS IN ('UNPAID', 'PAID')),

    CONSTRAINT CHK_MAINT_BILL_METHOD
        CHECK (
            PAYMENT_METHOD IN
            ('CASH', 'BANK_TRANSFER', 'CARD', 'ONLINE')
        ),

    CONSTRAINT CHK_MAINT_BILL_PAYMENT
        CHECK
        (
            (
                PAYMENT_STATUS = 'UNPAID'
                AND PAYMENT_DATE IS NULL
                AND PAYMENT_METHOD IS NULL
            )
            OR
            (
                PAYMENT_STATUS = 'PAID'
                AND PAYMENT_DATE IS NOT NULL
                AND PAYMENT_METHOD IS NOT NULL
            )
        )
);

-- =====================================
-- TABLE 11: COMPLAINT
-- =====================================

CREATE TABLE COMPLAINT
(
    COMPLAINT_ID NUMBER,

    COMPLAINT_CATEGORY VARCHAR2(50) NOT NULL,

    ISSUE_DESCRIPTION VARCHAR2(500) NOT NULL,

    DATE_REPORTED DATE DEFAULT SYSDATE NOT NULL,

    DATE_RESOLVED DATE,

    COMPLAINT_STATUS VARCHAR2(20)
        DEFAULT 'OPEN' NOT NULL,

    HOUSE_ID NUMBER NOT NULL,

    CONSTRAINT PK_COMPLAINT
        PRIMARY KEY (COMPLAINT_ID),

    CONSTRAINT FK_COMPLAINT_HOUSE
        FOREIGN KEY (HOUSE_ID)
        REFERENCES HOUSE(HOUSE_ID),

    CONSTRAINT CHK_COMPLAINT_STATUS
        CHECK
        (
            COMPLAINT_STATUS IN
            (
                'OPEN',
                'IN_PROGRESS',
                'RESOLVED',
                'CLOSED'
            )
        ),

    CONSTRAINT CHK_COMPLAINT_DATES
        CHECK
        (
            DATE_RESOLVED IS NULL
            OR DATE_RESOLVED >= DATE_REPORTED
        ),

    CONSTRAINT CHK_COMPLAINT_RESOLUTION
        CHECK
        (
            (
                COMPLAINT_STATUS IN ('OPEN', 'IN_PROGRESS')
                AND DATE_RESOLVED IS NULL
            )
            OR
            (
                COMPLAINT_STATUS IN ('RESOLVED', 'CLOSED')
                AND DATE_RESOLVED IS NOT NULL
            )
        )
);

