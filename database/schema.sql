-- =====================================
-- TABLE 13: BOOKING
-- =====================================

CREATE TABLE BOOKING
(
    BOOKING_ID NUMBER,

    BOOKING_DATE DATE DEFAULT SYSDATE NOT NULL,

    EVENT_TIME_START DATE NOT NULL,

    EVENT_TIME_END DATE NOT NULL,

    TOTAL_CALCULATED_FEE NUMBER(10,2)
        DEFAULT 0 NOT NULL,

    PAYMENT_STATUS VARCHAR2(10)
        DEFAULT 'UNPAID' NOT NULL,

    BOOKING_STATUS VARCHAR2(12)
        DEFAULT 'PENDING' NOT NULL,

    FACILITY_ID NUMBER NOT NULL,

    HOUSE_ID NUMBER NOT NULL,

    CONSTRAINT PK_BOOKING
        PRIMARY KEY (BOOKING_ID),

    CONSTRAINT FK_BOOKING_FACILITY
        FOREIGN KEY (FACILITY_ID)
        REFERENCES FACILITY(FACILITY_ID),

    CONSTRAINT FK_BOOKING_HOUSE
        FOREIGN KEY (HOUSE_ID)
        REFERENCES HOUSE(HOUSE_ID),

    CONSTRAINT CHK_BOOKING_TIME
        CHECK (EVENT_TIME_END > EVENT_TIME_START),

    CONSTRAINT CHK_BOOKING_FEE
        CHECK (TOTAL_CALCULATED_FEE >= 0),

    CONSTRAINT CHK_BOOKING_PAYMENT_STATUS
        CHECK (PAYMENT_STATUS IN ('UNPAID', 'PAID')),

    CONSTRAINT CHK_BOOKING_STATUS
        CHECK (
            BOOKING_STATUS IN
            (
                'PENDING',
                'APPROVED',
                'CANCELLED',
                'COMPLETED'
            )
        )
);
