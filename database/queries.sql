-- QUERY 53: DETECT OVERLAPPING BOOKINGS

SELECT
    B1.FACILITY_ID,
    B1.BOOKING_ID AS FIRST_BOOKING,
    B2.BOOKING_ID AS SECOND_BOOKING,
    B1.EVENT_TIME_START,
    B1.EVENT_TIME_END,
    B2.EVENT_TIME_START,
    B2.EVENT_TIME_END
FROM BOOKING B1
JOIN BOOKING B2
    ON B1.FACILITY_ID = B2.FACILITY_ID
   AND B1.BOOKING_ID < B2.BOOKING_ID
WHERE B1.BOOKING_STATUS IN ('PENDING', 'APPROVED')
  AND B2.BOOKING_STATUS IN ('PENDING', 'APPROVED')
  AND B1.EVENT_TIME_START < B2.EVENT_TIME_END
  AND B1.EVENT_TIME_END > B2.EVENT_TIME_START;


-- QUERY 54: AUDIT HOUSE OCCUPANCY STATUS

SELECT
    H.HOUSE_ID,
    H.HOUSE_NO,
    H.OCCUPANCY_STATUS
FROM HOUSE H
WHERE
(
    H.OCCUPANCY_STATUS = 'VACANT'
    AND EXISTS
    (
        SELECT 1
        FROM RESIDENT R
        WHERE R.HOUSE_ID = H.HOUSE_ID
          AND R.MOVE_IN_DATE <= SYSDATE
          AND (
              R.MOVE_OUT_DATE IS NULL
              OR R.MOVE_OUT_DATE > SYSDATE
          )
    )
)
OR
(
    H.OCCUPANCY_STATUS = 'OWNER-OCCUPIED'
    AND NOT EXISTS
    (
        SELECT 1
        FROM RESIDENT R
        WHERE R.HOUSE_ID = H.HOUSE_ID
          AND R.OWNER_ID = H.OWNER_ID
          AND R.RELATION_TYPE = 'OWNER'
          AND R.MOVE_IN_DATE <= SYSDATE
          AND (
              R.MOVE_OUT_DATE IS NULL
              OR R.MOVE_OUT_DATE > SYSDATE
          )
    )
)
OR
(
    H.OCCUPANCY_STATUS = 'TENANT-OCCUPIED'
    AND NOT EXISTS
    (
        SELECT 1
        FROM LEASE L
        JOIN RESIDENT R
            ON R.TENANT_ID = L.TENANT_ID
           AND R.HOUSE_ID = L.HOUSE_ID
        WHERE L.HOUSE_ID = H.HOUSE_ID
          AND L.LEASE_STATUS = 'ACTIVE'
          AND R.RELATION_TYPE = 'TENANT'
          AND R.MOVE_IN_DATE <= SYSDATE
          AND (
              R.MOVE_OUT_DATE IS NULL
              OR R.MOVE_OUT_DATE > SYSDATE
          )
    )
);
