WITH EXPECTED_TABLES AS
(
    SELECT 'OWNER' AS TABLE_NAME FROM DUAL
    UNION ALL SELECT 'TENANT' FROM DUAL
    UNION ALL SELECT 'EMPLOYEE' FROM DUAL
    UNION ALL SELECT 'FACILITY' FROM DUAL
    UNION ALL SELECT 'HOUSE' FROM DUAL
    UNION ALL SELECT 'LEASE' FROM DUAL
    UNION ALL SELECT 'RESIDENT' FROM DUAL
    UNION ALL SELECT 'VEHICLE' FROM DUAL
    UNION ALL SELECT 'VISITOR' FROM DUAL
    UNION ALL SELECT 'MAINTENANCE_BILL' FROM DUAL
    UNION ALL SELECT 'COMPLAINT' FROM DUAL
    UNION ALL SELECT 'COMPLAINT_ASSIGNMENT' FROM DUAL
    UNION ALL SELECT 'BOOKING' FROM DUAL
)
SELECT
    E.TABLE_NAME,
    CASE
        WHEN T.TABLE_NAME IS NOT NULL
        THEN 'EXISTS'
        ELSE 'MISSING'
    END AS TABLE_STATUS
FROM EXPECTED_TABLES E
LEFT JOIN USER_TABLES T
    ON E.TABLE_NAME = T.TABLE_NAME
ORDER BY E.TABLE_NAME;

